def patch_backend_wgpu_native():
    """Patch the api for the wgpu_native backend in backends/wgpu_native/_api.py."""

    # Get API dict
    api_base = read_definition_file("wgpu_api.toml")
    diff_wgpu_native = read_definition_file("diff_backend_wgpu_native.toml")
    api = dict_deep_merge(api_base, diff_wgpu_native)
    print(f"Found {len(api['classes'])} classes in the wgpu_native backend API")

    # Create parser object
    header_source = _get_wgpu_header(
        get_header_filename("webgpu.h"), get_header_filename("wgpu.h")
    )
    hp = HParser(header_source)
    hp.parse()

    # Check and write mappings
    compare_flags(api["flags"], hp)
    write_enum_mappings(api["enums"], hp)

    # The api patch itself
    patch_backend_api(api, hp)


def patch_backend_api(api, hp):
    implemented = detect_implemented_properties_and_methods(
        read_file("wgpu", "_classes.py")
    )

    filename_parts = "wgpu", "backends", "wgpu_native", "_api.py"
    code = read_file(*filename_parts)

    for patcher in [
        CommentRemover(("# FIXME: unknown C", "# FIXME: invalid C", "# H:")),
        ApiPatcher(api, True, implemented),
        StructValidationChecker(api),
        CStructPatcher(hp),
        FunctionPatcher(hp),
    ]:
        patcher.apply(code)
        code = patcher.dumps()

    write_file(code, *filename_parts)


mappings_preamble = '''
""" Mappings for the wgpu-native backend. """

# THIS CODE IS AUTOGENERATED - DO NOT EDIT

'''.lstrip()


def compare_flags(flags_dict: dict, hp: HParser):
    """For each flag in WebGPU:

    * Verify that there is a corresponding flag in webgpu.h/wgpu.h
    * Verify that all fields are present too.
    * Verify that the (integer) value is equal.

    """

    name_map = {
        "ColorWrite": "ColorWriteMask",
    }

    for name, flag_dict in flags_dict.items():
        name = name_map.get(name, name)
        if name not in hp.flags:
            print(f"Flag {name} missing in webgpu.h/wgpu.h")
        else:
            for key, flag in flag_dict["fields"].items():
                val = flag["value"]
                key = key.title().replace("_", "")  # MAP_READ -> MapRead
                key = name_map.get(f"{name}.{key}") or key
                if key not in hp.flags[name]:
                    print(f"Flag field {name}.{key} missing in webgpu.h/wgpu.h")
                elif val != hp.flags[name][key]:
                    print(f"Warning: Flag field {name}.{key} have different values.")


def write_enum_mappings(enums_dict: dict, hp: HParser):
    """Generate the file with dicts to map enums strings to ints. This
    also compares the enums in wgpu-native with WebGPU, and reports any
    missing ones.
    """

    # These maps are empty and thus not used, since no name mapping is (currently) necessary.
    name_map = {}
    name_map_i = {v: k for k, v in name_map.items()}

    # Init generated code
    pylines = [mappings_preamble]

    # Create enummap, which allows the wgpu-native backend to resolve enum field names
    # to the corresponding integer value.
    # We only include enums and enum fields that are defined in webgpu.h, so any
    # code written against wgpu-py is maximally compatible.
    enummap = {}
    for name, enum_dict in enums_dict.items():
        hname = name_map.get(name, name)
        native_name = "Native" + hname
        if hname not in hp.enums:
            print(f"Enum {hname} missing in webgpu.h")
            continue
        hp_enum = {key.lower(): val for key, val in hp.enums[hname].items()}
        # When a value is present *also* in wgpu.h, it overrides the value, whereby we
        # assume that's the value wgpu-native will most likely accept. This was introduced
        # to cover 16-norm TextureFormats, ref https://github.com/pygfx/wgpu-py/pull/805.
        if native_name in hp.enums:
            for key, val in hp.enums[native_name].items():
                key = key.lower()
                if key in hp_enum and val != hp_enum.get(key):
                    print(f"Enum field {name}.{key} overridden by wgpu.h")
                    hp_enum[key] = val
        for e in enum_dict["fields"].values():
            ikey = e["value"]
            hkey = ikey.lower().replace("-", "")
            hkey = name_map.get(f"{name}.{hkey}") or hkey
            if hkey in hp_enum:
                enummap[name + "." + ikey] = hp_enum[hkey]
            else:
                print(f"Enum field {name}.{ikey} missing in webgpu.h")

    # Write enummap
    pylines.append(f"# There are {len(enummap)} enum mappings\n")
    pylines.append("enummap = {")
    for key in sorted(enummap.keys()):
        pylines.append(f'    "{key}": {enummap[key]!r},')
    pylines.append("}\n")

    # Some structs have fields that are enum values. The wgpu-native backend
    # must be able to resolve these too.
    cstructfield2enum = {}
    for structname, struct in hp.structs.items():
        for key, val in struct.items():
            if isinstance(val, str) and val.startswith("WGPU"):
                henumname = val[4:].split("/")[0]
                enumname = name_map_i.get(henumname, henumname)
                if enumname in enums_dict:
                    cstructfield2enum[f"{structname[4:]}.{key}"] = enumname
                else:
                    pass  # a struct

    # Write cstructfield2enum
    pylines.append(f"# There are {len(cstructfield2enum)} struct-field enum mappings\n")
    pylines.append("cstructfield2enum = {")
    for key in sorted(cstructfield2enum.keys()):
        pylines.append(f'    "{key}": {cstructfield2enum[key]!r},')
    pylines.append("}\n")

    # Write a few native-only mappings: key => int
    pylines.append("enum_str2int = {")
    for name, use_snake in (
        ("BackendType", False),
        ("NativeFeature", True),
        ("PipelineStatisticName", True),
        ("Dx12Compiler", False),
        ("PolygonMode", False),
    ):
        pylines.append(f'    "{name}":' + " {")
        for key, val in hp.enums[name].items():
            if key == "Force32":
                continue
            if use_snake:
                key = to_snake_case(key).replace("_", "-")
            pylines.append(f'        "{key}": {val},')
        pylines.append("    },")
    pylines.append("}")
    pylines.append("")

    # Write a few native-only mappings: int => key
    # If possible, resolve to WebGPU names, otherwise use the native name.
    pylines.append("enum_int2str = {")
    for name in [
        "BackendType",
        "AdapterType",
        "ErrorType",
        "DeviceLostReason",
        "TextureFormat",
        "TextureDimension",
        "PresentMode",
        "CompositeAlphaMode",
        "SurfaceGetCurrentTextureStatus",
    ]:
        webgpu_names = {}
        if name in enums_dict:
            enum_fields = enums_dict[name]["fields"]
            webgpu_names = {
                val["value"].replace("-", ""): val["value"]
                for val in enum_fields.values()
            }
            if "unknown" in webgpu_names:
                webgpu_names["undefined"] = "unknown"
        pylines.append(f'    "{name}":' + " {")
        for key, val in hp.enums[name].items():
            if key == "Force32":
                continue
            enum_val = webgpu_names.get(key.lower(), key)
            pylines.append(f'        {val}: "{enum_val}",')
        pylines.append("    },")
    pylines.append("}")
    pylines.append("")

    # Write a few native-only flags
    pylines.append("native_flags = {")
    for name in [
        "InstanceBackend",
        "InstanceFlag",
    ]:
        for key, val in hp.flags[name].items():
            if key == "Force32":
                continue
            pylines.append(f'    "{name}.{key}": {val},')
    pylines.append("}")
    pylines.append("")

    # Wrap up
    print(
        f"Mapping {len(enummap)} enum mappings and {len(cstructfield2enum)} struct-field mappings"
    )
    code = format_code("\n".join(pylines))
    write_file(code, "wgpu", "backends", "wgpu_native", "_mappings.py")


