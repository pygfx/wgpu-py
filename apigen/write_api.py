"""Generate the simple API from the definitions."""

import re

from apigen_utils import (
    dict_deep_merge,
    format_code,
    # indent_code,
    read_definition_file,
    read_file,
    write_file,
)


def write_api():
    """Write the Python code for the flags, enums, and structs."""

    api = read_definition_file("wgpu_api.json")

    # Flags, enums, and structs (and their fields) defined in specific backends are added to the global set of flags/enums/structs,
    # but they'll each have a '_ext' suffix
    for fname in ["diff_backend_pyodide.json", "diff_backend_wgpu.json"]:
        extra_api = read_definition_file(fname)
        api = dict_deep_merge(api, extra_api)

    write_flags(api["flags"])
    write_enums(api["enums"])
    write_structs(api["structs"])


ref_pattern = re.compile(
    r"\W((GPU|classes\.|flags\.|enums\.|structs\.)\w+?)\W", re.MULTILINE
)


def resolve_crossrefs(text):
    text += " "
    i2 = 0
    while True:
        m = ref_pattern.search(text, i2)
        if not m:
            break
        i1, i2 = m.start(1), m.end(1)
        ref = m.group(1)
        ref = "." + ref.strip("`").lstrip(".")  # Leading dot means fuzzy search
        text = text[:i1] + "`" + ref + "`" + text[i2:]
        i2 += len(ref)
    return text.rstrip()


def write_flags(flags_dict):
    # Get preamble
    pylines = []
    for line in read_file("wgpu", "flags.py").splitlines():
        pylines.append(line)
        if "AUTOGENERATED" in line:
            pylines += ["", ""]
            break

    # List'm
    n = len(flags_dict)
    pylines.append(f"# There are {n} flags\n")
    pylines.append("__all__ = [")
    for name in sorted(flags_dict.keys()):
        pylines.append(f'    "{name}",')
    pylines.append("]\n\n")

    # The flags definitions
    for name, flag_dict in flags_dict.items():
        pylines.append(f"{name}Flags = int | str\n\n")
        pylines.append(f"class {name}(Flags):\n")
        # pylines.append(f'    """{indent_code(flag_dict["doc"])}"""')
        for field_name, field_dict in flag_dict["fields"].items():
            pylines.append(
                f"    {field_name} = {field_dict['value']!r}"
            )  # " #: {field_dict['doc']}")
        pylines.append("\n")

    # Write
    code = format_code("\n".join(pylines))
    write_file(code, "wgpu", "flags.py")
    print(f"Wrote {n} flags to flags.py")


def write_enums(enums_dict):
    # Get preamble
    pylines = []
    for line in read_file("wgpu", "enums.py").splitlines():
        pylines.append(line)
        if "AUTOGENERATED" in line:
            pylines += ["", ""]
            break

    # List'm
    n = len(enums_dict)
    pylines.append(f"# There are {n} enums\n")
    pylines.append("__all__ = [")
    for name in sorted(enums_dict.keys()):
        pylines.append(f'    "{name}",')
    pylines.append("]\n\n")

    # The enum definitions
    for name, enum_dict in enums_dict.items():
        quoted_values = [f'"{f["value"]}"' for f in enum_dict["fields"].values()]
        pylines.append(f"{name}Enum = Literal[{', '.join(quoted_values)}] | str\n\n")
        pylines.append(f"class {name}(Enum):\n")
        # pylines.append(f'    """{indent_code(enum_dict["doc"])}"""')
        for field_name, field_dict in enum_dict["fields"].items():
            pylines.append(
                f'    {field_name} = "{field_dict["value"]}"'
            )  # " #: {field_dict["doc"]}'')
        pylines.append("\n")

    # Write
    code = format_code("\n".join(pylines))
    write_file(code, "wgpu", "enums.py")
    print(f"Wrote {n} enums to enums.py")


def write_structs(structs_dict):
    # Get preamble
    pylines = []
    for line in read_file("wgpu", "structs.py").splitlines():
        pylines.append(line)
        if "AUTOGENERATED" in line:
            pylines += ["", ""]
            break

    # List'm
    n = len(structs_dict)
    pylines.append(f"# There are {n} structs\n")
    pylines.append("__all__ = [")
    for name in sorted(structs_dict.keys()):
        pylines.append(f'    "{name}",')
    pylines.append("]\n\n")

    # The struct definitions
    for name, struct_dict in structs_dict.items():
        pylines.append(f"@dataclass(kw_only=True, repr=False)\nclass {name}(Struct):")
        # pylines.append(f'    """{indent(struct_dict["doc"])}"""')
        for field_name, field_dict in struct_dict["fields"].items():
            # Get type to include in code, and massage a bit for this module
            raw_type = field_dict["type"]
            code_type = raw_type.replace("GPU", "classes.GPU").replace("structs.", "")
            code_type = code_type.replace("list[", "Sequence[")
            # Get type to include in docs
            docs_type = ""
            if (
                "flags." in raw_type
                or "enums." in raw_type
                or "structs." in raw_type
                or "classes." in raw_type
            ):
                docs_type = raw_type.replace("Flags", "").replace("Enum", "")
                docs_type = resolve_crossrefs(f" {docs_type} ")
            # Get default and massage it a bit
            default = field_dict["default"]
            if default == "[]":
                default = "()"
            elif default == "{}":
                default = "None"  # no mutable defaults
            if default == "None" and "None" not in code_type:
                code_type += " | None"
            # Build docs
            doc = ""
            if docs_type:
                doc += f"{docs_type.strip()} "
            if default:
                pylines.append(
                    f"    #: {doc}\n    {field_name}: {code_type} = {default}"
                )
            else:
                pylines.append(f"    #: {doc}\n    {field_name}: {code_type}")
        if len(struct_dict) == 0:
            pylines.append("    pass")
        pylines.append("\n")
        pylines.append(f"{name}Struct = {name} | dict")

    # Write
    code = format_code("\n".join(pylines))
    write_file(code, "wgpu", "structs.py")
    print(f"Wrote {n} structs to structs.py")


if __name__ == "__main__":
    write_api()
