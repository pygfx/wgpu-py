from apigen_utils import read_definition_file, read_file, write_file, dict_deep_merge, format_code, indent


def write_api():
    api_without_docs = read_definition_file("wgpu_api.toml")
    docs = read_definition_file("wgpu_docs.toml")

    api = dict_deep_merge(api_without_docs, docs, allow_add=False)

    print(t1-t0)
    write_flags(api['flags'])
    write_enums(api['enums'])


def write_flags(flags_dict):
    # Get preamble
    pylines = []
    for line in read_file("wgpu", "flags.py").splitlines():
        pylines.append(line)
        if "AUTOGENERATED" in line:
            pylines += ["", ""]
            break

    # List'm
    n = len(flags_dict)
    pylines.append(f"# There are {n} flags\n")
    pylines.append("__all__ = [")
    for name in sorted(flags_dict.keys()):
        pylines.append(f'    "{name}",')
    pylines.append("]\n\n")

    # The flags definitions
    for name, flag_dict in flags_dict.items():
        # Generate Code
        pylines.append(f"{name}Flags = int | str\n\n")
        pylines.append(f"class {name}(Flags):\n")
        pylines.append(f'    """{indent(flag_dict["doc"])}"""')
        for field_name, field_dict in flag_dict['fields'].items():
            pylines.append(f"    {field_name} = {field_dict['value']!r}  #: {field_dict['doc']}")  # note: can add docs using "#: "
        pylines.append("\n")

    # Write
    code = format_code("\n".join(pylines))
    write_file(code, "wgpu", "flags.py")
    print(f"Wrote {n} flags to flags.py")


