"""
Apply codegen to the Dawn backend.

The Dawn backend uses the cdef in dawn_bindings/src/wgpu_dawn/webgpu_cdef.h,
which is generated from Emdawnwebgpu's webgpu.h (a strict subset of Dawn's
native webgpu.h). This module:

* Writes backends/dawn/_mappings.py (enum str <-> int) from that header.
* Annotates/validates the C calls and structs in backends/dawn/_api.py, using
  the same logic as for the wgpu-native backend, but against Dawn's header.
"""

import os
import re
from contextlib import contextmanager

from codegen.utils import print, format_code
from codegen.hparser import HParser
from codegen.idlparser import get_idl_parser
from codegen.files import file_cache, lib_dir
from codegen import wgpu_native_patcher


mappings_preamble = '''
""" Mappings for the Dawn backend. """

# THIS CODE IS AUTOGENERATED - DO NOT EDIT

'''.lstrip()

_dawn_parser = None


def get_dawn_h_parser():
    global _dawn_parser
    if _dawn_parser is None:
        filename = os.path.join(
            lib_dir, "..", "dawn_bindings", "src", "wgpu_dawn", "webgpu_cdef.h"
        )
        with open(filename, "rb") as f:
            source = f.read().decode()
        # The cffi "extern Python" lines are not part of the API
        source = "\n".join(
            line for line in source.splitlines() if not line.startswith("extern ")
        )
        source = re.sub(r"\s+;", ";", source)
        _dawn_parser = HParser(source)
        _dawn_parser.parse(verbose=False)
    return _dawn_parser


@contextmanager
def _use_dawn_header():
    ori = wgpu_native_patcher.get_h_parser
    wgpu_native_patcher.get_h_parser = get_dawn_h_parser
    try:
        yield
    finally:
        wgpu_native_patcher.get_h_parser = ori


def _kebab(name):
    from codegen.utils import to_snake_case

    return to_snake_case(name).replace("_", "-")


def write_mappings():
    """Write backends/dawn/_mappings.py."""

    idl = get_idl_parser()
    hp = get_dawn_h_parser()

    pylines = [mappings_preamble]

    # enummap: WebGPU enum names -> int, for enums in webgpu.h
    enummap = {}
    for name in idl.enums:
        if name not in hp.enums:
            print(f"Enum {name} missing in Dawn's webgpu.h")
            continue
        hp_enum = {
            key.lower().replace("_", ""): val for key, val in hp.enums[name].items()
        }
        for ikey in idl.enums[name].values():
            hkey = ikey.lower().replace("-", "")
            if hkey in hp_enum:
                enummap[name + "." + ikey] = hp_enum[hkey]
            else:
                print(f"Enum field {name}.{ikey} missing in Dawn's webgpu.h")

    pylines.append(f"# There are {len(enummap)} enum mappings\n")
    pylines.append("enummap = {")
    for key in sorted(enummap.keys()):
        pylines.append(f'    "{key}": {enummap[key]!r},')
    pylines.append("}\n")

    # Struct fields that are enums
    cstructfield2enum = {}
    for structname, struct in hp.structs.items():
        for key, val in struct.items():
            if isinstance(val, str) and val.startswith("WGPU"):
                enumname = val[4:].split("/")[0]
                if enumname in idl.enums:
                    cstructfield2enum[f"{structname[4:]}.{key}"] = enumname

    pylines.append(f"# There are {len(cstructfield2enum)} struct-field enum mappings\n")
    pylines.append("cstructfield2enum = {")
    for key in sorted(cstructfield2enum.keys()):
        pylines.append(f'    "{key}": {cstructfield2enum[key]!r},')
    pylines.append("}\n")

    # str -> int for a few enums, including values that are not in WebGPU
    pylines.append("enum_str2int = {")
    for name, use_kebab in (("BackendType", False), ("FeatureName", True)):
        pylines.append(f'    "{name}":' + " {")
        for key, val in hp.enums[name].items():
            if key == "Force32":
                continue
            if use_kebab:
                key = _kebab(key)
            pylines.append(f'        "{key}": {val},')
        pylines.append("    },")
    pylines.append("}")
    pylines.append("")

    # int -> str, using WebGPU names where possible
    pylines.append("enum_int2str = {")
    for name in [
        "BackendType",
        "AdapterType",
        "ErrorType",
        "DeviceLostReason",
        "TextureFormat",
        "TextureDimension",
        "PresentMode",
        "CompositeAlphaMode",
        "SurfaceGetCurrentTextureStatus",
    ]:
        webgpu_names = {}
        if name in idl.enums:
            webgpu_names = {
                val.replace("-", ""): val for val in idl.enums[name].values()
            }
            if "unknown" in webgpu_names:
                webgpu_names["undefined"] = "unknown"
        pylines.append(f'    "{name}":' + " {")
        for key, val in hp.enums[name].items():
            if key == "Force32":
                continue
            enum_val = webgpu_names.get(key.lower(), key)
            pylines.append(f'        {val}: "{enum_val}",')
        pylines.append("    },")
    pylines.append("}")
    pylines.append("")

    code = format_code("\n".join(pylines))
    file_cache.write("backends/dawn/_mappings.py", code)
    print(
        f"Wrote {len(enummap)} enum mappings and {len(cstructfield2enum)} struct-field mappings to dawn/_mappings.py"
    )


def compare_flags():
    with _use_dawn_header():
        wgpu_native_patcher.compare_flags()


def patch_dawn_backend(code):
    """Annotate C calls and struct instantiations, validated against Dawn's webgpu.h."""
    with _use_dawn_header():
        return wgpu_native_patcher.patch_wgpu_native_backend(code)
